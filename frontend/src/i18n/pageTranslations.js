function translateNode(node, dictionary) {
  const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
  const textNodes = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode);
  textNodes.forEach((textNode) => {
    const value = textNode.nodeValue.trim();
    if (!value) return;
    if (dictionary[value]) {
      textNode.nodeValue = textNode.nodeValue.replace(value, dictionary[value]);
      return;
    }
    const statusValue = langStatus(value, dictionary === hi ? "hi" : "en");
    if (statusValue) {
      textNode.nodeValue = textNode.nodeValue.replace(value, statusValue);
      return;
    }
    const translated = patterns[dictionary === hi ? "hi" : "en"].find(([pattern]) => pattern.test(value));
    if (translated) textNode.nodeValue = textNode.nodeValue.replace(value, value.replace(translated[0], translated[1]));
  });

  node.querySelectorAll?.("input[placeholder], textarea[placeholder]").forEach((input) => {
    if (dictionary[input.placeholder]) input.placeholder = dictionary[input.placeholder];
  });
}

function langStatus(value, lang) {
  if (lang === "hi") return statusTranslations[value];
  return Object.entries(statusTranslations).find(([, translated]) => translated === value)?.[0];
}

export function applyPageLanguage(lang) {
  if (typeof document === "undefined") return;
  translateNode(document.body, lang === "hi" ? hi : en);
}
